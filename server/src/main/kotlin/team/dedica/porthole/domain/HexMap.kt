package team.dedica.porthole.domain

import com.fasterxml.jackson.annotation.JsonCreator
import com.fasterxml.jackson.annotation.JsonProperty

/**
 * The hex grid map. Tiles are stored by their axial coordinate.
 *
 * Jackson serialises [allTiles] as "tiles" so the client can iterate
 * the collection without knowing the internal map structure.
 * The [JsonCreator] annotation allows Jackson to reconstruct a [HexMap]
 * from the same "tiles" list during deserialisation.
 */
class HexMap @JsonCreator constructor(@JsonProperty("tiles") tiles: List<HexTile>) {
    // internal so that the persistence layer can store the tileMap directly
    internal val tileMap: MutableMap<HexCoordinate, HexTile> =
        tiles.associateBy { it.coordinate }.toMutableMap()

    @get:JsonProperty("tiles")
    val allTiles: Collection<HexTile> get() = tileMap.values
    val size: Int get() = tileMap.size
    fun getTile(coordinate: HexCoordinate): HexTile? = tileMap[coordinate]
    fun getNeighbours(coordinate: HexCoordinate): List<HexTile> =
        coordinate.neighbours().mapNotNull { tileMap[it] }

    fun setTile(coordinate: HexCoordinate, tile: HexTile) {
        tileMap[coordinate] = tile
    }

    fun isAdjacent(a: HexCoordinate, b: HexCoordinate): Boolean =
        a.distanceTo(b) == 1

    /**
     * Regenerates the terrain and elevation of this map from scratch based on
     * existing landmarks and groups.
     */
    fun regenerateTerrain(
        landmarks: Collection<Landmark> = emptyList(),
        groups: Collection<LandmarkGroup> = emptyList(),
        seed: Long = java.util.concurrent.ThreadLocalRandom.current().nextLong(),
        cols: Int? = null,
        rows: Int? = null,
    ): HexMap = MapTerrainGenerator.regenerateTerrain(this, landmarks, groups, seed, cols, rows).map

    companion object {
        /** Classic hexagonal map (used by tests). */
        fun createHexagonal(
            radius: Int,
            elevationFn: (HexCoordinate) -> Int = { 0 },
            terrainFn: (HexCoordinate) -> Terrain = { Terrain.GRASS },
        ): HexMap {
            val tiles = mutableListOf<HexTile>()
            for (q in -radius..radius) {
                val r1 = maxOf(-radius, -q - radius)
                val r2 = minOf(radius, -q + radius)
                for (r in r1..r2) {
                    val coord = HexCoordinate(q, r)
                    tiles += HexTile(
                        coordinate = coord,
                        elevation = elevationFn(coord).coerceIn(0, 5),
                        terrain = terrainFn(coord),
                    )
                }
            }
            return HexMap(tiles)
        }

        /**
         * Rectangular offset grid of [cols] x [rows] hex tiles with
         * Perlin-noise elevation. Elevation == 0 means water (not walkable).
         */
        fun createGrid(cols: Int, rows: Int, seed: Long = 42L): HexMap {
            val noise = PerlinNoise(seed)
            val tiles = mutableListOf<HexTile>()
            val qOffset = cols / 2
            val rOffset = rows / 2
            for (col in 0 until cols) {
                for (row in 0 until rows) {
                    val q = col - qOffset
                    val r = row - rOffset - (q - (q and 1)) / 2
                    val coord = HexCoordinate(q, r)
                    val scale = 4.0
                    val nx = col.toDouble() / cols * scale
                    val ny = row.toDouble() / rows * scale
                    val raw = noise.octave(nx, ny, octaves = 6, persistence = 0.5, lacunarity = 2.0)
                    // Map [-1,1] to [0,5]. Values below 0.3 (normalised) become water (0).
                    val normalised = (raw + 1.0) / 2.0   // 0..1
                    val elev = if (normalised < 0.35) 0
                    else ((normalised - 0.35) / 0.65 * 5.0).toInt().coerceIn(1, 5)
                    val terrain = when {
                        normalised < 0.35 -> Terrain.WATER
                        normalised < 0.50 -> Terrain.GRASS
                        normalised < 0.70 -> Terrain.FOREST
                        else -> Terrain.ROCKS
                    }
                    tiles += HexTile(coordinate = coord, elevation = elev, terrain = terrain)
                }
            }
            return HexMap(tiles)
        }

        /**
         * Sea map: mostly water with a handful of small islands.
         *
         * Islands are generated by placing random "seed" points and building a
         * raised Perlin-noise blob around each one. Island edges become BEACH,
         * the interior is GRASS, SWAMP or ROCKS depending on a second noise layer.
         */
        fun createSeaGrid(cols: Int, rows: Int, seed: Long = 42L): HexMap {
            val rng = java.util.Random(seed)
            val noise = PerlinNoise(seed)
            val noise2 = PerlinNoise(seed xor 0xDEAD_BEEF)

            // How many islands (roughly 1 per 400 tiles, min 3, max 12)
            val islandCount = (cols * rows / 400).coerceIn(3, 12)

            // Island centres in grid space (col, row)
            data class IslandSeed(val col: Double, val row: Double, val radius: Double)

            val margin = 4
            val islands = List(islandCount) {
                IslandSeed(
                    col = margin + rng.nextDouble() * (cols - 2 * margin),
                    row = margin + rng.nextDouble() * (rows - 2 * margin),
                    radius = 2.0 + rng.nextDouble() * 4.0,   // 2..6 tiles radius
                )
            }

            val qOffset = cols / 2
            val rOffset = rows / 2
            val tiles = mutableListOf<HexTile>()

            for (col in 0 until cols) {
                for (row in 0 until rows) {
                    val q = col - qOffset
                    val r = row - rOffset - (q - (q and 1)) / 2
                    val coord = HexCoordinate(q, r)

                    // Island influence: max over all island seeds of a Gaussian blob
                    // combined with a small Perlin wobble to make jagged shores.
                    val wobble = noise.octave(
                        col.toDouble() / cols * 6.0,
                        row.toDouble() / rows * 6.0,
                        octaves = 4, persistence = 0.5, lacunarity = 2.0,
                    ) * 1.5   // [-1.5, 1.5]

                    val influence = islands.maxOf { isl ->
                        val dx = col - isl.col
                        val dy = row - isl.row
                        val dist = Math.sqrt(dx * dx + dy * dy)
                        // Gaussian falloff + wobble to break symmetry
                        val adjusted = dist - wobble
                        1.0 - (adjusted / isl.radius).coerceAtLeast(0.0)
                    }

                    // Interior noise for terrain variety inside the island
                    val interior = noise2.octave(
                        col.toDouble() / cols * 8.0,
                        row.toDouble() / rows * 8.0,
                        octaves = 3, persistence = 0.5, lacunarity = 2.0,
                    ) // [-1, 1]
                    val interiorN = (interior + 1.0) / 2.0  // 0..1

                    val (terrain, elev) = when {
                        influence < 0.15 -> Terrain.WATER to 0
                        influence < 0.45 -> Terrain.BEACH to 1
                        else -> when {
                            interiorN < 0.30 -> Terrain.SWAMP to 1
                            interiorN < 0.65 -> Terrain.GRASS to (2 + (interiorN * 3).toInt()).coerceIn(2, 4)
                            else -> Terrain.ROCKS to (3 + (interiorN * 2).toInt()).coerceIn(3, 5)
                        }
                    }

                    tiles += HexTile(coordinate = coord, elevation = elev, terrain = terrain)
                }
            }
            return HexMap(tiles)
        }

        fun createBlankGrid(cols: Int, rows: Int): HexMap {
            val qOffset = cols / 2
            val rOffset = rows / 2
            val tiles = mutableListOf<HexTile>()
            for (col in 0 until cols) {
                for (row in 0 until rows) {
                    val q = col - qOffset
                    val r = row - rOffset - (q - (q and 1)) / 2
                    tiles += HexTile(coordinate = HexCoordinate(q, r), elevation = 1, terrain = Terrain.GRASS)
                }
            }
            return HexMap(tiles)
        }
    }
}
