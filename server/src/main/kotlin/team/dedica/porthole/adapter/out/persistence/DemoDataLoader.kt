        addStageConnectionUseCase.execute(DEMO_MAP_ID, diagId, orderId, connExam1Lab,  "Blood / urine sample", "FORWARD", UN_PETRA)
        addStageConnectionUseCase.execute(DEMO_MAP_ID, diagId, orderId, connExam2Xray, "Imaging request",      "FORWARD", UN_PETRA)

